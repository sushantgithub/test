def rotate_options(q, k):
    """Spread correct answers across A–D so position is not a giveaway."""
    letters = ["A", "B", "C", "D"]
    k = k % 4
    if k == 0:
        return q
    values = [q["options"][L] for L in letters]
    new_vals = values[k:] + values[:k]
    mapping = {letters[i]: letters[(i - k) % 4] for i in range(4)}
    return {
        **q,
        "options": dict(zip(letters, new_vals)),
        "correct": mapping[q["correct"]],
        "incorrectExplanations": [
            {"options": [mapping[x] for x in item["options"]], "text": item["text"]}
            for item in q["incorrectExplanations"]
        ],
    }


NEW_QUESTIONS = [rotate_options(q, i) for i, q in enumerate(NEW_QUESTIONS)]


def assert_count():
    if len(NEW_QUESTIONS) != 90:
        raise SystemExit(f"Expected 90 new questions, got {len(NEW_QUESTIONS)}")


if __name__ == "__main__":
    assert_count()
    from collections import Counter
    print(len(NEW_QUESTIONS), "new questions")
    print(Counter(q["correct"] for q in NEW_QUESTIONS))
    print(Counter(q["domain"] for q in NEW_QUESTIONS))
